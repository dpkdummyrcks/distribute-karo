#!/usr/bin/env node
// Writes infra/.env.api (gitignored, mode 600) for local dev from infra/.env plus the Garage key.
// Keeps an existing JWT keypair and HMAC secret so sessions survive a re-run. Prints key names only.
import { execFileSync } from 'node:child_process';
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const infra = join(dirname(fileURLToPath(import.meta.url)), '..');
const parse = (file) =>
  Object.fromEntries(
    readFileSync(file, 'utf8')
      .split('\n')
      .filter((l) => /^[A-Z_]+=/.test(l))
      .map((l) => {
        const i = l.indexOf('=');
        return [l.slice(0, i), l.slice(i + 1).replace(/^"(.*)"$/, '$1')];
      }),
  );

const env = parse(join(infra, '.env'));
const outFile = join(infra, '.env.api');
const prev = existsSync(outFile) ? parse(outFile) : {};
const s3 = {};
for (const line of execFileSync('sh', [join(infra, 'scripts/garage-bootstrap.sh')], { encoding: 'utf8' }).split('\n')) {
  const m = /^(S3_ACCESS_KEY|S3_SECRET_KEY)=(.+)$/.exec(line);
  if (m) s3[m[1]] = m[2];
}
if (!s3.S3_ACCESS_KEY || !s3.S3_SECRET_KEY) throw new Error('garage-bootstrap.sh did not return S3 keys');

let { JWT_PRIVATE_KEY: priv, JWT_PUBLIC_KEY: pub, HMAC_SECRET: hmac } = prev;
if (!priv || !pub) {
  const kp = generateKeyPairSync('ed25519', {
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    publicKeyEncoding: { type: 'spki', format: 'pem' },
  });
  priv = kp.privateKey.trim().replaceAll('\n', '\\n');
  pub = kp.publicKey.trim().replaceAll('\n', '\\n');
}
hmac ??= randomBytes(32).toString('hex');

const u = encodeURIComponent;
const pgPort = env.POSTGRES_HOST_PORT ?? '55432';
const values = {
  NODE_ENV: 'development',
  PORT: prev.PORT ?? '3000',
  DATABASE_URL: `postgres://dk_app:${u(env.DK_APP_PASSWORD)}@127.0.0.1:${pgPort}/${env.POSTGRES_DB}`,
  DATABASE_MIGRATION_URL: `postgres://dk_owner:${u(env.DK_OWNER_PASSWORD)}@127.0.0.1:${pgPort}/${env.POSTGRES_DB}`,
  VALKEY_URL: `redis://:${u(env.VALKEY_PASSWORD)}@127.0.0.1:${env.VALKEY_HOST_PORT ?? '56379'}`,
  S3_ENDPOINT: `http://127.0.0.1:${env.GARAGE_S3_HOST_PORT ?? '53900'}`,
  S3_BUCKET: env.GARAGE_BUCKET ?? 'dk-media',
  S3_ACCESS_KEY: s3.S3_ACCESS_KEY,
  S3_SECRET_KEY: s3.S3_SECRET_KEY,
  PUBLIC_BASE_URL: prev.PUBLIC_BASE_URL ?? 'http://localhost:5173',
  JWT_PRIVATE_KEY: priv,
  JWT_PUBLIC_KEY: pub,
  HMAC_SECRET: hmac,
  TRUSTED_PROXIES: '127.0.0.1/32',
};
const body = Object.entries(values)
  .map(([k, v]) => (k.startsWith('JWT_') ? `${k}="${v}"` : `${k}=${v}`))
  .join('\n');
writeFileSync(outFile, `# Generated by infra/scripts/gen-api-env.mjs. Gitignored. Do not commit.\n${body}\n`, {
  mode: 0o600,
});
chmodSync(outFile, 0o600);
console.log(`wrote infra/.env.api: ${Object.keys(values).join(', ')}`);
