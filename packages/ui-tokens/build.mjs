#!/usr/bin/env node
// Generates tokens for both platforms from tokens.json (ADR-008):
//   generated/tokens.css  → Tailwind v4 @theme + dark overrides (retailer web)
//   generated/DkTokens.kt → Compose colour schemes + status colours (distributor app),
//                           also copied into the Android app when it exists.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const HEADER = 'GENERATED by packages/ui-tokens/build.mjs from tokens.json. Do not edit.';

// ---------- CSS (Tailwind v4)
const css = [];
css.push(`/* ${HEADER} */`, '@theme {');
for (const [k, v] of Object.entries(t.color.light)) css.push(`  --color-${kebab(k)}: ${v};`);
for (const [s, v] of Object.entries(t.status)) {
  css.push(
    `  --color-status-${kebab(s.toLowerCase())}: ${v.light[0]};`,
    `  --color-on-status-${kebab(s.toLowerCase())}: ${v.light[1]};`,
  );
}
for (const [k, v] of Object.entries(t.radius)) css.push(`  --radius-${k}: ${v === 999 ? '9999px' : `${v}px`};`);
css.push(`  --font-display: ${t.font.display.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};`);
css.push(`  --font-body: ${t.font.body.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};`);
for (const [k, v] of Object.entries(t.type))
  css.push(
    `  --text-${k}: ${v.size}px;`,
    `  --text-${k}--line-height: ${v.line}px;`,
    `  --text-${k}--font-weight: ${v.weight};`,
  );
css.push('}', '');
const darkVars = [];
for (const [k, v] of Object.entries(t.color.dark)) darkVars.push(`  --color-${kebab(k)}: ${v};`);
for (const [s, v] of Object.entries(t.status)) {
  darkVars.push(
    `  --color-status-${kebab(s.toLowerCase())}: ${v.dark[0]};`,
    `  --color-on-status-${kebab(s.toLowerCase())}: ${v.dark[1]};`,
  );
}
css.push(
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  ...darkVars.map((l) => `  ${l}`),
  '  }',
  '}',
  '',
);
css.push(':root[data-theme="dark"] {', ...darkVars, '}', '');

// ---------- Kotlin (Compose Material 3)
const argb = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const scheme = (c) =>
  [
    `primary = ${argb(c.primary)}`,
    `onPrimary = ${argb(c.onPrimary)}`,
    `primaryContainer = ${argb(c.primaryContainer)}`,
    `onPrimaryContainer = ${argb(c.onPrimaryContainer)}`,
    `secondary = ${argb(c.accent)}`,
    `onSecondary = ${argb(c.onAccent)}`,
    `secondaryContainer = ${argb(c.accentSoft)}`,
    `onSecondaryContainer = ${argb(c.onAccentSoft)}`,
    `background = ${argb(c.background)}`,
    `onBackground = ${argb(c.text)}`,
    `surface = ${argb(c.background)}`,
    `onSurface = ${argb(c.text)}`,
    `surfaceVariant = ${argb(c.surfaceHigh)}`,
    `onSurfaceVariant = ${argb(c.text2)}`,
    `surfaceContainerLowest = ${argb(c.sheet)}`,
    `surfaceContainerLow = ${argb(c.surface)}`,
    `surfaceContainer = ${argb(c.surface)}`,
    `surfaceContainerHigh = ${argb(c.surfaceHigh)}`,
    `surfaceContainerHighest = ${argb(c.surfaceHigh)}`,
    `outline = ${argb(c.outlineStrong)}`,
    `outlineVariant = ${argb(c.outline)}`,
    `error = ${argb(c.danger)}`,
    `onError = ${argb(c.onDanger)}`,
    `errorContainer = ${argb(c.dangerContainer)}`,
    `onErrorContainer = ${argb(c.onDangerContainer)}`,
    `inverseSurface = ${argb(c.inverseSurface)}`,
    `inverseOnSurface = ${argb(c.onInverseSurface)}`,
  ]
    .map((l) => `        ${l},`)
    .join('\n');
const statusEntries = (mode) =>
  Object.entries(t.status)
    .map(
      ([s, v]) =>
        `            OrderStatusKey.${s} to StatusColors(container = ${argb(v[mode][0])}, content = ${argb(v[mode][1])}),`,
    )
    .join('\n');
const ext = (c) =>
  [
    'accent',
    'onAccent',
    'success',
    'successContainer',
    'onSuccessContainer',
    'warning',
    'warningContainer',
    'onWarningContainer',
  ]
    .map((k) => `        ${k} = ${argb(c[k])},`)
    .join('\n');
// tokens.json type roles → Material 3 slots
const TYPE_SLOTS = {
  display: 'displaySmall',
  headline: 'headlineMedium',
  title: 'titleLarge',
  body: 'bodyLarge',
  label: 'labelLarge',
  caption: 'bodySmall',
};
const typeSlots = Object.entries(TYPE_SLOTS)
  .map(([role, slot]) => {
    const r = t.type[role];
    return `        ${slot} = TextStyle(fontSize = ${r.size}.sp, lineHeight = ${r.line}.sp, fontWeight = FontWeight(${r.weight})),`;
  })
  .join('\n');
const kt = `// ${HEADER}
package \`in\`.distributekaro.app.core.designsystem

import androidx.compose.material3.Typography
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

enum class OrderStatusKey { ${Object.keys(t.status).join(', ')} }

data class StatusColors(val container: Color, val content: Color)

/** Colours Material 3 has no slot for. */
data class DkExtendedColors(
    val accent: Color,
    val onAccent: Color,
    val success: Color,
    val successContainer: Color,
    val onSuccessContainer: Color,
    val warning: Color,
    val warningContainer: Color,
    val onWarningContainer: Color,
    val status: Map<OrderStatusKey, StatusColors>,
)

object DkTokens {
    val LightColors = lightColorScheme(
${scheme(t.color.light)}
    )

    val DarkColors = darkColorScheme(
${scheme(t.color.dark)}
    )

    val LightExtended = DkExtendedColors(
${ext(t.color.light)}
        status = mapOf(
${statusEntries('light')}
        ),
    )

    val DarkExtended = DkExtendedColors(
${ext(t.color.dark)}
        status = mapOf(
${statusEntries('dark')}
        ),
    )

    /** Type scale from tokens.json; font families are applied by DkTheme. */
    val Typography = Typography(
${typeSlots}
    )

    object Radius {
${Object.entries(t.radius)
  .map(([k, v]) => `        const val ${k.toUpperCase()} = ${v}`)
  .join('\n')}
    }
}
`;

mkdirSync(join(here, 'generated'), { recursive: true });
writeFileSync(join(here, 'generated/tokens.css'), css.join('\n'));
writeFileSync(join(here, 'generated/DkTokens.kt'), kt);
const androidDir = join(
  here,
  '../../apps/distributor-android/app/src/main/java/in/distributekaro/app/core/designsystem',
);
if (existsSync(androidDir)) writeFileSync(join(androidDir, 'DkTokens.kt'), kt);
console.log(`tokens → generated/tokens.css, generated/DkTokens.kt${existsSync(androidDir) ? ' (+ Android app)' : ''}`);
